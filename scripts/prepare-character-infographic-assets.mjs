// Pack native infographic PNGs for the web and generate the shared, accessible catalog.
// Requires a local Sharp installation; neither Docker builds nor runtime need Node/Sharp.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const toolsDir = process.argv.find(arg => arg.startsWith('--tools-dir='))?.slice('--tools-dir='.length)
    ?? path.join(root, '.tools/character-previews');
const sharp = createRequire(path.join(path.resolve(toolsDir), 'package.json'))('sharp');
const assetDir = path.join(root, 'assets/characters/raymond');
const entries = [];
for (const part of ['a', 'b', 'c']) {
    const manifest = JSON.parse(await fs.readFile(path.join(assetDir, `sql-infographics-20261108-${part}.json`), 'utf8'));
    if (manifest.generator !== 'builtin-imagegen') throw new Error('Unexpected generator provenance.');
    entries.push(...manifest.entries);
}
entries.sort((a, b) => a.id.localeCompare(b.id));
if (entries.length !== 16 || new Set(entries.map(item => item.id)).size !== 16)
    throw new Error('Expected sixteen unique teaching infographics.');
const coverage = new Set(entries.flatMap(item => item.objectives));
if (coverage.size !== 24 || [...coverage].some(value => !Number.isInteger(value) || value < 1 || value > 24))
    throw new Error('The series must introduce all twenty-four supplied learning objectives.');

const report = [];
const catalog = [];
const lines = [];
const q = value => JSON.stringify(value ?? '');
const strings = values => '[' + values.map(q).join(', ') + ']';
const hash = value => createHash('sha256').update(value).digest('hex');
for (const item of entries) {
    if (!/^\d{2}-[a-z0-9-]+$/.test(item.id) || item.image !== `/images/characters/raymond/infographics/${item.id}.png`)
        throw new Error(`Unexpected asset identity: ${item.id}`);
    if (!['H1', 'H2', 'H3'].includes(item.stage) || !item.title || !item.alt?.startsWith('Raymond')
        || !item.summary || item.explanation?.length < 3 || !item.prompt || !item.sourceArtifact
        || !item.text?.length || !item.sources?.length)
        throw new Error(`Incomplete teaching metadata: ${item.id}`);
    for (const source of item.sources)
        if (!source.label || new URL(source.href).protocol !== 'https:') throw new Error(`Invalid source: ${item.id}`);
    const input = path.join(root, 'web/wwwroot', item.image);
    const original = await fs.readFile(input);
    const metadata = await sharp(original).metadata();
    if (metadata.format !== 'png' || metadata.width !== item.width || metadata.height !== item.height
        || item.width < 1440 || Math.abs(item.width / item.height - 1.5) > 0.02)
        throw new Error(`Expected a native landscape 3:2 PNG: ${item.id}`);
    const preview = item.image.replace(/\.png$/, '.webp');
    const output = path.join(root, 'web/wwwroot', preview);
    await sharp(original).resize({ width: 1200, withoutEnlargement: true })
        .webp({ quality: 92, effort: 6 }).toFile(output);
    const webp = await fs.readFile(output);
    const previewMetadata = await sharp(webp).metadata();
    if (!(await fs.readFile(input)).equals(original)) throw new Error(`Original modified: ${item.id}`);
    report.push({ id: item.id, image: item.image, preview, width: item.width, height: item.height,
        previewWidth: previewMetadata.width, previewHeight: previewMetadata.height,
        originalBytes: original.length, previewBytes: webp.length,
        originalSha256: hash(original), previewSha256: hash(webp) });
    const { prompt, sourceArtifact, text, ...teachingMetadata } = item;
    catalog.push({ ...teachingMetadata, preview });
    const sources = '[' + item.sources.map(source => `new(${q(source.label)}, ${q(source.href)})`).join(', ') + ']';
    lines.push(`        new("raymond", ${q(item.id)}, ${q(item.title)}, ${q(item.image)}, ${q(preview)}, ${q(item.alt)}, ${item.width}, ${item.height}, ${q(item.stage)}, [${item.objectives.join(', ')}], ${q(item.summary)}, ${strings(item.explanation)}, ${q(item.sql)}, ${sources})`);
}
const generated = `// Generated by scripts/prepare-character-infographic-assets.mjs. Prompts and native PNGs are preserved separately.
namespace Mercantec.Tech.Contracts;

public static class CharacterInfographicCatalog
{
    public static IReadOnlyList<CharacterInfographicAsset> All { get; } = Array.AsReadOnly<CharacterInfographicAsset>(
    [
${lines.join(',\n')}
    ]);
}

public sealed record CharacterInfographicSource(string Label, string Href);
public sealed record CharacterInfographicAsset(string CharacterSlug, string Id, string Title, string Image,
    string Preview, string Alt, int Width, int Height, string Stage, IReadOnlyList<int> Objectives,
    string Summary, IReadOnlyList<string> Explanation, string Sql, IReadOnlyList<CharacterInfographicSource> Sources);
`;
await fs.writeFile(path.join(root, 'shared/CharacterInfographicCatalog.cs'), generated);
await fs.writeFile(path.join(assetDir, 'sql-infographics-catalog.json'), JSON.stringify({ schemaVersion: 1,
    generatedOn: '2026-11-08', courseId: '16474', courseName: 'Databaseprogrammering',
    description: 'Introduktioner og fagligt overblik til de 24 oplyste målpinde, ikke dokumentation for opnået kompetence.',
    entries: catalog }, null, 2) + '\n');
await fs.writeFile(path.join(assetDir, 'sql-infographics-preview-report.json'), JSON.stringify(report, null, 2) + '\n');
const originalBytes = report.reduce((total, item) => total + item.originalBytes, 0);
const previewBytes = report.reduce((total, item) => total + item.previewBytes, 0);
console.log(JSON.stringify({ count: entries.length, objectives: coverage.size, originalBytes, previewBytes }));
