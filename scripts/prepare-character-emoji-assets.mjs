// Web packaging only: original generated PNGs are never changed.
// Setup: npm install --prefix .tools/character-previews sharp@0.35.5
// Run: node scripts/prepare-character-emoji-assets.mjs
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(root, '.tools/character-previews/package.json'));
const sharp = require('sharp');
const catalog = JSON.parse(await fs.readFile(path.join(root, 'assets/characters/reactions-catalog.json'), 'utf8'));
const reusePreviews = process.argv.includes('--reuse-previews');
const addNew = process.argv.includes('--add-new');
if (reusePreviews && addNew) throw new Error('Choose either --reuse-previews or --add-new.');
const previous = reusePreviews || addNew
    ? JSON.parse(await fs.readFile(path.join(root, 'assets/characters/reactions-preview-report.json'), 'utf8')) : [];
const previousByImage = new Map(previous.map(item => [item.image, item]));
const lines = [];
const report = [];
for (const asset of catalog.entries) {
    if (!/^\/images\/characters\/(raymond|beaver|fox|lupp)\/reactions\/[a-z0-9-]+\.png(?:\?v=[a-f0-9]+)?$/.test(asset.image))
        throw new Error(`Unexpected image path: ${asset.image}`);
    const input = path.join(root, 'web/wwwroot', asset.image.split('?')[0]);
    const output = input.replace(/\.png$/, '.webp');
    const before = await fs.readFile(input);
    const metadata = await sharp(before).metadata();
    if (metadata.width !== asset.width || metadata.height !== asset.height || !metadata.hasAlpha)
        throw new Error(`Dimensions or alpha mismatch: ${asset.image}`);
    const prior = previousByImage.get(asset.image);
    const useExisting = reusePreviews || (addNew && prior !== undefined);
    if (!useExisting) {
        await sharp(before).resize({ width: 512, height: 512, fit: 'inside', withoutEnlargement: true })
            .webp({ quality: 88, alphaQuality: 100, effort: 6 }).toFile(output);
    }
    const preview = await fs.readFile(output);
    if (useExisting) {
        if (!prior || prior.originalSha256 !== createHash('sha256').update(before).digest('hex')
            || prior.previewSha256 !== createHash('sha256').update(preview).digest('hex'))
            throw new Error(`Changed or missing known image; regenerate without reuse flags: ${asset.image}`);
    }
    const after = await fs.readFile(input);
    if (!before.equals(after)) throw new Error(`Original PNG was modified: ${asset.image}`);
    lines.push(`        new(new(${JSON.stringify(asset.guid)}), ${JSON.stringify(asset.character)}, ${JSON.stringify(asset.name)}, ${JSON.stringify(asset.title)}, ${JSON.stringify(asset.image)}, ${JSON.stringify(asset.alt)}) { PreviewSizeBytes = ${preview.length} }`);
    report.push({ image: asset.image, preview: asset.image.replace('.png', '.webp'), originalBytes: before.length,
        previewBytes: preview.length, originalSha256: createHash('sha256').update(before).digest('hex'),
        previewSha256: createHash('sha256').update(preview).digest('hex') });
}
const code = `// Generated by scripts/prepare-character-emoji-assets.mjs from assets/characters/reactions-catalog.json.\nnamespace Mercantec.Tech.Contracts;\n\npublic static class CharacterEmojiCatalog\n{\n    public static IReadOnlyList<CharacterEmojiAsset> All { get; } = Array.AsReadOnly<CharacterEmojiAsset>(\n    [\n${lines.join(',\n')}\n    ]);\n}\n\npublic sealed record CharacterEmojiAsset(Guid Id, string CharacterSlug, string Name, string Title, string Image, string Alt)\n{\n    public int Width => 1254;\n    public int Height => 1254;\n    public string Preview => Image.Replace(".png", ".webp", StringComparison.Ordinal);\n    public long PreviewSizeBytes { get; init; }\n}\n`;
await fs.writeFile(path.join(root, 'shared/CharacterEmojiCatalog.cs'), code);
await fs.writeFile(path.join(root, 'assets/characters/reactions-preview-report.json'), JSON.stringify(report, null, 2) + '\n');
const originalBytes = report.reduce((sum, item) => sum + item.originalBytes, 0);
const previewBytes = report.reduce((sum, item) => sum + item.previewBytes, 0);
console.log(JSON.stringify({ count: report.length, originalBytes, previewBytes, reduction: `${(100 - previewBytes / originalBytes * 100).toFixed(1)}%` }));
