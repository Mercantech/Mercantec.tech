// Web packaging and catalog generation. Native imagegen PNGs are read but never changed.
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { openCharacterOriginal } from './character-originals.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sharp = createRequire(path.join(root, '.tools/character-previews/package.json'))('sharp');
const assets = path.join(root, 'assets/characters/chameleon');
const manifest = JSON.parse(await fs.readFile(path.join(assets, 'ml-infographics.json'), 'utf8'));
if (manifest.generator !== 'builtin-imagegen' || manifest.entries.length !== 16)
    throw new Error('Expected sixteen separately generated ML infographics.');
const q = value => JSON.stringify(value ?? '');
const hash = data => createHash('sha256').update(data).digest('hex');
const strings = values => '[' + values.map(q).join(', ') + ']';
const report = [];
async function packagePng(image, width, height, previewWidth) {
    const source = await openCharacterOriginal(image);
    const original = source.bytes;
    const metadata = await sharp(original).metadata();
    if (metadata.format !== 'png' || metadata.width !== width || metadata.height !== height)
        throw new Error(`Unexpected native PNG dimensions: ${image}`);
    const preview = image.replace(/\.png$/, '.webp');
    await sharp(original).resize({ width: previewWidth, withoutEnlargement: true })
        .webp({ quality: 92, effort: 6 }).toFile(path.join(root, 'web/wwwroot', preview));
    const webp = await fs.readFile(path.join(root, 'web/wwwroot', preview));
    await source.verifyUnchanged?.();
    report.push({ image, preview, width, height, originalBytes: original.length, previewBytes: webp.length,
        originalSha256: hash(original), previewSha256: hash(webp) });
    return preview;
}
const lines = [];
const ids = new Set();
for (const item of manifest.entries) {
    if (!/^\d{2}-[a-z0-9-]+$/.test(item.id) || ids.has(item.id)
        || item.image !== `/images/characters/chameleon/infographics/${item.id}.png`
        || !item.sourceArtifact || !item.prompt || !item.title || !item.alt?.startsWith('Kamæleonen')
        || !item.summary || item.explanation?.length < 3 || !item.sources?.length
        || item.width < 1440 || Math.abs(item.width / item.height - 1.5) > .02)
        throw new Error(`Incomplete teaching asset: ${item.id}`);
    ids.add(item.id);
    for (const source of item.sources)
        if (!source.label || new URL(source.href).protocol !== 'https:') throw new Error(`Invalid source: ${item.id}`);
    const preview = await packagePng(item.image, item.width, item.height, 1200);
    const sources = '[' + item.sources.map(s => `new(${q(s.label)}, ${q(s.href)})`).join(', ') + ']';
    lines.push(`        new("chameleon", ${q(item.id)}, ${q(item.title)}, ${q(item.image)}, ${q(preview)}, ${q(item.alt)}, ${item.width}, ${item.height}, "ML", [], ${q(item.summary)}, ${strings(item.explanation)}, ${q(item.example)}, ${sources})`);
}
const artwork = JSON.parse(await fs.readFile(path.join(assets, 'artwork.json'), 'utf8'));
if (artwork.generator !== 'builtin-imagegen' || artwork.entries.length !== 7)
    throw new Error('Expected three portrait variants and four illustrated settings.');
for (const item of artwork.entries) {
    if (!item.image?.startsWith('/images/characters/chameleon/') || !item.prompt || !item.sourceArtifact)
        throw new Error(`Incomplete artwork provenance: ${item.id}`);
    await packagePng(item.image, item.width, item.height, item.width === item.height ? 768 : 1200);
}
await packagePng('/images/characters/chameleon/portrait.png', 1254, 1254, 768);
await fs.writeFile(path.join(root, 'shared/ChameleonInfographicCatalog.cs'), `// Generated by scripts/prepare-chameleon-assets.mjs. Native PNGs and prompts are preserved separately.
namespace Mercantec.Tech.Contracts;

public static class ChameleonInfographicCatalog
{
    public static IReadOnlyList<CharacterInfographicAsset> All { get; } = Array.AsReadOnly<CharacterInfographicAsset>(
    [
${lines.join(',\n')}
    ]);
}
`);
await fs.writeFile(path.join(assets, 'preview-report.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify({ infographics: ids.size, portraits: 4, scenes: 4,
    originalBytes: report.reduce((n, r) => n + r.originalBytes, 0),
    previewBytes: report.reduce((n, r) => n + r.previewBytes, 0) }));
