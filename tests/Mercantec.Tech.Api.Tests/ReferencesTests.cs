    private static void Replace(byte[] bytes, string from, string to)
    {
        var source = System.Text.Encoding.UTF8.GetBytes(from); var target = System.Text.Encoding.UTF8.GetBytes(to);
        Assert.Equal(source.Length, target.Length);
        var at = bytes.AsSpan().IndexOf(source); Assert.True(at >= 0);
        target.CopyTo(bytes.AsSpan(at));
    }
