    [Fact]
    public async Task CrossDomainEdgesAndBacklinksDisappearWhenSourceShareIsRevoked()
    {
        await service.BaselineNotionAsync(page.Id, default);
        await db.NotionPages.Where(p => p.Id == page.Id).ExecuteUpdateAsync(s => s.SetProperty(p => p.PublishedState, State(BothState)));
        await service.RefreshNotionAsync(page.Id, default, published: true);
        var graph = await service.GraphAsync(User(student), new(Focus: Ref("notebook-page", noteId)), default);
        Assert.Contains(graph.Edges, e => e.FromKey == Ref("notion-page", page.Id).Key && e.ToKey == Ref("notebook-page", noteId).Key);
        Assert.Single(await service.BacklinksAsync(User(student), Ref("notebook-page", noteId), false, default));
        var ownerNotebook = new Notebook { Id = Guid.NewGuid(), OwnerSub = outsider };
        var otherNote = new NotebookDocument { Id = Guid.NewGuid(), Notebook = ownerNotebook, Title = "Delt kilde", YjsState = State(BothState) };
        db.NotebookDocuments.Add(otherNote);
        db.NotebookShares.Add(new() { Id = Guid.NewGuid(), NotebookId = ownerNotebook.Id, RecipientSub = student });
        await db.SaveChangesAsync();
        await service.BaselineNotebookAsync(otherNote.Id, default);
        var before = await service.BacklinksAsync(User(student), Ref("notebook-page", noteId), false, default);
        Assert.Contains(before, r => r.Reference == Ref("notebook-page", otherNote.Id));
        await db.NotebookShares.Where(s => s.NotebookId == ownerNotebook.Id).ExecuteDeleteAsync();
        var after = await service.BacklinksAsync(User(student), Ref("notebook-page", noteId), false, default);
        Assert.DoesNotContain(after, r => r.Reference == Ref("notebook-page", otherNote.Id));
    }

