    {
        var refs = new HashSet<EntityReference>();
        Assert.True(YjsPageLinks.TryReadReferences(State(BothState), "notion-page", refs));
        Assert.Contains(Ref("person", student), refs); Assert.Contains(Ref("notebook-page", noteId), refs);
        refs.Clear(); Assert.True(YjsPageLinks.TryReadReferences(State(DeletedPersonState), "notion-page", refs));
