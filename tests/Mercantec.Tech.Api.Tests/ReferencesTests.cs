    [Fact]
    public async Task LegacyMembershipMentionNotifiesItsLinkedAccount()
    {
        var membershipId = await db.Memberships.Select(m => m.Id).SingleAsync();
        var state = State(PersonState);
        Replace(state, "person", "member"); Replace(state, student.ToString("D"), membershipId.ToString("D"));
        await service.BaselineNotionAsync(page.Id, default);
        await db.NotionPages.Where(p => p.Id == page.Id).ExecuteUpdateAsync(s => s.SetProperty(p => p.PublishedState, state));
