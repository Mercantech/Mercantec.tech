    [Fact]
    public async Task PendingMentionAppearsAfterShareAndRemovalStartsANewSingleEpisode()
    {
        var owner = new Notebook { Id = Guid.NewGuid(), OwnerSub = outsider };
        var source = new NotebookDocument { Id = Guid.NewGuid(), Notebook = owner, Title = "Delt senere", YjsState = GraphFixtures.Get("empty") };
        db.NotebookDocuments.Add(source); await db.SaveChangesAsync();
        await service.BaselineNotebookAsync(source.Id, default);
        await db.NotebookDocuments.Where(d => d.Id == source.Id).ExecuteUpdateAsync(s => s.SetProperty(d => d.YjsState, State(PersonState)));
        await service.RefreshNotebookAsync(source.Id, default);
        var pending = Assert.Single(await db.ReferenceMentionEvents.ToArrayAsync());
        Assert.Empty(await service.MentionsAsync(User(student), default));
        await service.AcknowledgeMentionsAsync(User(student), [new("mention", pending.Id)], default);
        Assert.Empty(await db.ActionReadReceipts.ToArrayAsync());
        db.NotebookShares.Add(new() { Id = Guid.NewGuid(), NotebookId = owner.Id, RecipientSub = student }); await db.SaveChangesAsync();
        Assert.Single(await service.MentionsAsync(User(student), default));
        await db.NotebookDocuments.Where(d => d.Id == source.Id).ExecuteUpdateAsync(s => s.SetProperty(d => d.YjsState, GraphFixtures.Get("empty")));
        await service.RefreshNotebookAsync(source.Id, default);
        Assert.Empty(await db.ReferenceMentionEvents.ToArrayAsync());
        await db.NotebookDocuments.Where(d => d.Id == source.Id).ExecuteUpdateAsync(s => s.SetProperty(d => d.YjsState, State(PersonState)));
        await service.RefreshNotebookAsync(source.Id, default);
        var current = Assert.Single(await service.MentionsAsync(User(student), default)); Assert.NotEqual(pending.Id, current.ResourceId);
        await service.AcknowledgeMentionsAsync(User(student), [new("mention", current.ResourceId)], default);
        await service.AcknowledgeMentionsAsync(User(student), [new("mention", current.ResourceId)], default);
        Assert.Single(await db.ActionReadReceipts.ToArrayAsync()); Assert.Empty(await service.MentionsAsync(User(student), default));
    }

